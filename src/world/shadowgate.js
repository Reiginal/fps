// 遠い方の影マップを「焼き直すべきか」だけを判定する門番。
//
// なぜ要るか: 太陽の影は距離で2枚に分けてあり（main.jsのCASCADES）、
// 遠い1枚(radius 56)は3フレームに1回、影を落とすメッシュ517枚を丸ごと焼き直していた。
// 太陽も地形も動かないのに、である。影マップを1枚焼くのは
// 「シーンの物を全部もう一度描く」ことなので、これは3フレームごとに
// 重いフレームが1回来る形になる。平均fpsには出ないのに体感はカクつく、の作り方そのもの。
//
// 判定の考え方:
//   ・地形は動かない。動くのは敵・死体・対戦の相手だけ
//   ・近い枚(radius 16、カメラ追従)の中は、近い枚が毎フレーム焼くので放っておける。
//     遠い枚の担当になるのは近い枚の外に居る物だけ
//   ・生きている敵と対戦の相手は、居るだけで姿勢が動き続ける（歩き・構え）ので、
//     遠くに1体でも居る間は今まで通りの間隔で焼き直す
//   ・落ち着いた死体(deathSettled)はもう1mmも動かない。位置の合計を「指紋」として
//     覚えておき、変わった時（死体が増えた・片付いた・カメラが動いて担当が替わった）
//     だけ焼き直す
//
// つまり悪くなる方向には倒れない: 全員が遠くで動き回る最悪の場面は今までと同じ頻度、
// 誰も遠くで動いていなければ0回になる。
//
// DOMにもthreeにも依存しない素の計算だけ。tools/check-shadowgate.mjs がここを叩く。

export class FarShadowGate {
  /**
   * @param near 近い枚に任せてよい半径(m)。近い枚の箱(半径16の正方形)に
   *   内接する円は半径16だが、箱の端はカーネルぶん使えない(main.jsのedge参照)し、
   *   背の高い物は太陽方向へ影がずれるので、余裕を持って内側に取る
   */
  constructor(near = 13) {
    this._near2 = near * near;
    this._baked = false;   // まだ1回も焼いていない（最初は必ず焼く）
    this._sig = 0;         // 最後に焼いた時の、止まった物の指紋
    this._liveNow = false;
    this._sigNow = 0;
    this._cx = 0;
    this._cz = 0;
  }

  /** 1回の判定を始める。カメラ（＝近い枚の中心）の位置を渡す */
  begin(camX, camZ) {
    this._cx = camX;
    this._cz = camZ;
    this._liveNow = false;
    this._sigNow = 0;
  }

  /**
   * 動く物を1つ数える。settledは「もう動かない」（落ち着いた死体）。
   * 毎回全部をadd()し直す。配列を作って渡す形にしないのは、
   * 呼ぶ側が毎フレーム配列を組み立てる（＝捨てる）ことになるため
   */
  add(x, z, settled) {
    const dx = x - this._cx;
    const dz = z - this._cz;
    if (dx * dx + dz * dz < this._near2) return;   // 近い枚の担当
    if (!settled) { this._liveNow = true; return; }
    /* 止まった物は位置を1つの数へ畳む。個々を覚えて突き合わせるより粗いが、
       知りたいのは「前に焼いた時から何か変わったか」だけなので指紋で足りる。
       係数を素数っぽくずらすのは、xとzの入れ替わりで偶然同じ値になるのを避けるため */
    this._sigNow += x * 31.7 + z * 17.3 + 1;
  }

  /** 焼き直すべきならtrue。trueを返した回は「この姿で焼いた」と覚える */
  end() {
    const bake = !this._baked || this._liveNow || this._sigNow !== this._sig;
    if (bake) {
      this._baked = true;
      this._sig = this._sigNow;
    }
    return bake;
  }
}
