// 太陽の向きと色。**遊びに来た時刻で変わる。**
//
// なぜ要るか: いつ来ても同じ夕方の街で、何回遊んでも同じ画だった。
// 時間帯が変わるだけで、同じマップが違う場所に見える。
//
// **本物の時計を使う。** 試合ごとに抽選する形にしなかったのは2つ理由がある。
//   1. 空も影も焼き上げは起動時に1回きりで、途中で変えるとそこを作り直す話になる。
//      「最低限」から外れる
//   2. 抽選だと、一緒に遊んでいる人と違う空が見える。時計なら、
//      同じ時間に遊んでいる人（＝身内はだいたい同じ地域）は同じ空になる
//
// **夜は作らない。** 暗くすると当てる所が見えなくなって、遊びとして別物になる。
// 実際の時刻が何時でも、朝・昼・夕方の3つのどれかへ寄せる。
// 夜に遊べば夕方の空になる（そこは嘘だが、遊べなくなるよりまし）。

/* 時間帯。dirは太陽の向き（正規化前でよい）、colorは日射しの色。
 *
 * 仰角がこの画の出来をほぼ決める。低いほど:
 *   ・影が手前に長く伸びて画面内に入る
 *   ・面ごとに明暗差がついて立体が起きる
 *   ・輪郭に逆光気味の縁が出る
 * 昼を高くしすぎると、影が物の真下に潰れて画が平らになる。
 * 0.46（約27度）が今まで使っていた値で、これを夕方に据えて、朝と昼を足した */
export const TIME_OF_DAY = [
  {
    id: 'morning',
    name: '朝',
    hours: [5, 10],           // 5時〜10時
    dir: [0.72, 0.38, -0.46],  // 東寄りの低い日
    color: 0xffe8cf,
  },
  {
    id: 'noon',
    name: '昼',
    hours: [10, 16],
    dir: [-0.34, 0.78, -0.52], // 高い日。影が短くなる
    color: 0xfff6e6,
  },
  {
    id: 'evening',
    name: '夕方',
    hours: [16, 5],            // 16時〜翌5時（夜もここへ寄せる）
    dir: [-0.78, 0.46, -0.34], // 今まで使っていた向き
    color: 0xfff0d8,
  },
];

/** idから引く。知らないidは夕方へ寄せる（今まで通りの画） */
export const timeOfDay = (id) => TIME_OF_DAY.find((t) => t.id === id) || TIME_OF_DAY[2];

/**
 * その時刻はどの時間帯か。
 *
 * 夕方だけ日をまたぐ（16時〜翌5時）ので、範囲の見方が他と違う。
 * ここを「開始 <= h && h < 終了」の1本で書くと、夜が必ずどこにも入らない
 */
export function timeOfDayAt(hour) {
  const h = Number.isFinite(hour) ? Math.floor(hour) % 24 : 18;
  const at = h < 0 ? h + 24 : h;
  for (const t of TIME_OF_DAY) {
    const [from, to] = t.hours;
    const hit = from < to ? (at >= from && at < to) : (at >= from || at < to);
    if (hit) return t;
  }
  return TIME_OF_DAY[2];
}

/** 今この端末の時刻の時間帯。ここだけが本物の時計を見る */
export const currentTimeOfDay = () => timeOfDayAt(new Date().getHours());
