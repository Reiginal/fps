// 他人が入力した文字列を innerHTML へ入れる前に無害にする。
//
// なぜ1箇所に置くか: 同じ表が lobby・chat・hud・diag の4ファイルに手書きで
// コピペされていて、account.js だけ ' も逃がす少し広い表になっていた。
// 安全装置が5つの写しに割れていると、1つの表から文字が漏れてもgrepでは気づけない。
// ここの表は一番広かった account.js の物（& < > " ' の5文字）に揃えてある。
// ' まで逃がすのは、属性を '...' で囲んだHTMLへ値を入れても壊れないようにするため。
// 見た目は変わらない（&#39; はブラウザが ' として描く）。
//
// サーバー側にも同じ物が server/logs.js に1つ居る。あちらはNodeだけで動く
// 管理画面で、読み込みの向き（server→src/ui）を増やしたくないので繋いでいない。

const ESC = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
export const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ESC[c]);
