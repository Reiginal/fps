/* **1人用だけ、波を凌ぐと武器が増える。**
   遊んで「第二波までいったらスナイパー使えるようにしてほしい」と言われた所。
   ずっと同じ4本だと、波が進んで敵が固くなるほど手札は変わらないままなので、
   進むほど「同じことを長くやる」だけになっていた。

   **増えた物は数字キーに割り当てない。** 一度5番へ足したが、
   「5押すのは流石に指的に遠い」「普通にQでスナイパーでいいんじゃね？」と言われて
   専用のキー(Q)へ移した。WASDから指を浮かせずに届くのがQまでで、
   1〜4の並びも動かないままになる。

   対戦では配らない（サーバーのserver/modes.jsが持ち物を決めていて、
   こちらを読まない）。増やしたくなったらあちらのcarryForを触る話になる */
export const SOLO_UNLOCKS = [
  { wave: 2, id: 'sniper' },
];

/**
 * その波の時点で解放されている武器の番号（数字キーの4本には入らない物）。
 * waveは今の波（1から数える。まだ始まっていなければ0）。
 *
 * 表を引くだけの関数にしてあるのは、**画面を持たない所から確かめられるようにする**ため。
 * main.jsの中に「波が2以上なら」と書くと、確かめるのにブラウザが要る
 */
export const soloUnlocksAt = (weapons, wave) => {
  const out = [];
  for (const u of SOLO_UNLOCKS) {
    if ((wave | 0) < u.wave) continue;
    const i = weapons.findIndex((w) => w.id === u.id);
    if (i >= 0 && !out.includes(i)) out.push(i);
  }
  return out;
};

