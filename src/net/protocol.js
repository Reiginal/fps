/**
 * 爆風の威力。中心から離れるほど線形に落ちて、MIN_DMGで止まる。
 *
 * **式をここ1つに集めてある。** 前は同じ式が3か所（1人用の爆発・サーバー・検査）に
 * 手で書かれていて、対戦だけ倍にしようとした時に書き換え漏れが必ず出る形だった。
 *
 * 対戦は体力が倍(HP)なので、同じ数字のままだと効きが半分になる。
 * 中心で一撃(170/130)だったものが、260に対して170＝2発要る物へ静かに変わり、
 * 「置きにいく」道具から「削るだけの道具」になってしまう。
 * だから体力と同じ倍率でそのまま持ち上げる（当たった時の割合を1人用と揃える）。
 *
 * @param dist 爆心からの距離。BLAST_Rより遠い相手はそもそも呼ばない
 * @param versus 対戦か。1人用の敵(enemy.js)は体力の作りが別なので倍にしない
 */
export const blastDamage = (dist, versus = false) => {
  const base = Math.max(NADE.MIN_DMG, NADE.BLAST_DMG * (1 - dist / NADE.BLAST_R));
  return versus ? base * (HP.VERSUS / HP.SOLO) : base;
};

