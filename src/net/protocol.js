/* ---------------------------------------------------------- 持ち物 */

// **武器の表(WEAPONS)にあることと、持って出られることは別。**
//
// 全部を常に持てる形にしていたら「ライフルとショットガンとピストルを
// 同時に持つのは無理がある。人はそんなに持てない」となった。実際その通りで、
// 主武器を2本担いだうえに拳銃まで下げている絵になっていた。
//
// なので**持ち物をここで絞る。** 表から消すのではなく、配る物を選ぶ形にする。
// 消してしまうと、ガンゲーム（キルごとに武器が替わる）で配れなくなるし、
// 将来「試合前に主武器を選ぶ」を入れる時にも作り直しになる。
//
// idで書くのは、番号だと武器を1本足しただけで全部ずれるため
// （実際ピストルを差し込んだ時に、番号を直書きしていた検査が嘘をつき始めた）。
//
// 並びがそのまま画面の1〜4のキーになる。
export const LOADOUT_IDS = ['rifle', 'pistol', 'knife', 'nade'];

/** 武器の表から、持って出る物の番号だけを取り出す */
export const loadoutOf = (weapons) => LOADOUT_IDS
  .map((id) => weapons.findIndex((w) => w.id === id))
  .filter((i) => i >= 0);

/* ------------------------------------------------ ソロで途中から増える物 */

/* **1人用だけ、波を凌ぐと持ち物が増える。**
   遊んで「第二波までいったらスナイパー使えるようにしてほしい」と言われた所。
   ずっと同じ4本だと、波が進んで敵が固くなるほど手札は変わらないままなので、
   進むほど「同じことを長くやる」だけになっていた。

   **持ち物の後ろに足す。** 前や途中へ差し込むと、既に体が覚えている
   1〜4の並びが波の途中で入れ替わることになる。
   足すだけなら、覚えた番号はそのままで新しい番号が1つ増える。

   対戦では配らない（サーバーのserver/modes.jsが持ち物を決めていて、
   こちらを読まない）。増やしたくなったらあちらのcarryForを触る話になる */
export const SOLO_UNLOCKS = [
  { wave: 2, id: 'sniper' },
];

/**
 * その波の時点でソロが持っている物の番号の並び。
 * waveは今の波（1から数える。まだ始まっていなければ0）。
 *
 * 表を引くだけの関数にしてあるのは、**画面を持たない所から確かめられるようにする**ため。
 * main.jsの中に「波が2以上なら」と書くと、確かめるのにブラウザが要る
 */
export const soloCarryAt = (weapons, wave) => {
  const carry = loadoutOf(weapons);
  for (const u of SOLO_UNLOCKS) {
    if ((wave | 0) < u.wave) continue;
    const i = weapons.findIndex((w) => w.id === u.id);
    if (i >= 0 && !carry.includes(i)) carry.push(i);
  }
  return carry;
};

