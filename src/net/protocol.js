/* ---------------------------------------------------------------- 送受信 */

export function encode(msg) { return JSON.stringify(msg); }

export function decode(raw) {
  try {
    const m = JSON.parse(typeof raw === 'string' ? raw : raw.toString());
    return (m && typeof m.t === 'string') ? m : null;
  } catch {
    return null;   // 壊れた電文で落ちない。無視して次を待つ
  }
}
