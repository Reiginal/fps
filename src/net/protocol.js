export const MAX_REWIND_MS = 300;

// 巻き戻し用に位置を残しておく長さ。上限より少し余裕を持たせる
export const HISTORY_MS = 500;

export const MAX_PLAYERS = 8;

// この秒数だけ何も届かなければ切れたとみなす
export const TIMEOUT_MS = 12000;

