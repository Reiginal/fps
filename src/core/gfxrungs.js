// 自動画質の「段」の表。0が全部入り、大きいほど軽い絵。
//
// なぜ切り出したか: 段の意味はmain.jsの_applyRungに直書きされていたが、
// **既定値を軽くした時に、既定と同じ内容の段が空回りになる**事故が起きた。
// 実際、既定がきめ細かさ85%だった頃に「段1=85%」があり、
// 既定でAOが切りなのに「段3=AO切り」があって、5段のうち2段が何もしない段だった。
// 一番効く段に届くまで最短32秒、そのうち16秒はただ待つだけ。
// 表をここへ出して、検査(tools/check-autoquality.mjs)が
// 「既定の設定に対して全部の段が実際に何かを削るか」を機械で見張る。
//
// 段の並べ方: 再コンパイルの要らない物（倍率・パスの入り切り）を先に、
// 影は後に（実行時に効くのはマップの粗さと焼く頻度だけなので、体感が跳ねる）。
// どの値もユーザーの設定より低い方へしか倒さない（Math.min／&&）。

export const MAX_RUNG = 4;

/**
 * 段rの時に実際へ適用する値を返す。
 * @param values 設定の値（settings.jsのloadSettings()の形）。無ければ既定扱い
 */
export function rungValues(values, r) {
  const v = values || {};
  // 倍率の上限。既定0.75に対して 1段=0.70 → 2段=0.60 → 4段=0.50 と必ず下がる
  const cap = r >= 4 ? 0.5 : r >= 2 ? 0.6 : r >= 1 ? 0.7 : 1;
  return {
    scale: Math.min(v.gfxScale ?? 1, cap),
    // AOとにじみは既定で切ってあるので、この段は「上げている人向け」。
    // 既定の人にはこの段でも倍率が下がる（capが段2で0.6になる）ので空回りしない
    ao: (v.gfxAo ?? false) && r < 2,
    bloom: (v.gfxBloom ?? false) && r < 2,
    shadow: r >= 3 ? '低' : (v.gfxShadow ?? '中'),
  };
}
